#Requires -Version 7.4.1
[CmdletBinding()]
param([ValidateSet('d3d12','vulkan','opengl')][string]$Driver = 'd3d12',
      [ValidateSet('safe')][string]$RenderThread='safe', [switch]$Runtime)
. "$PSScriptRoot/godot-fixture.ps1"
$ErrorActionPreference='Stop'
$root=Split-Path $PSScriptRoot -Parent
Push-Location $root
try {
    $suffix=if($Runtime){'-runtime'}else{''}
    $log=Join-Path $root "agentdir/logs/window-immediate-close-$Driver-$RenderThread$suffix.log"
    New-Item -ItemType Directory -Force (Split-Path $log) | Out-Null
    if($Runtime){
        $fixture=Join-Path $root 'artifacts/runtime-window-immediate-close'
        New-Item -ItemType Directory -Force $fixture | Out-Null
        Copy-Item -LiteralPath tests/godot/window_immediate_close.gd,tests/godot/window_immediate_close.tscn -Destination $fixture -Force
        [IO.File]::WriteAllText((Join-Path $fixture 'project.godot'), "config_version=5`n[application]`nrun/main_scene=`"res://window_immediate_close.tscn`"`n")
        # The scene fixture expects the script cache generated by the editor,
        # even though this fixture uses no global script classes.
        & ./godot/bin/godot.windows.editor.x86_64.console.exe --headless --path $fixture --editor --import *> "$log.import"
        if($LASTEXITCODE -ne 0){throw "Runtime fixture import failed: $log.import"}
        Push-Location $fixture
        try {
            Invoke-GodotFixture -Driver $Driver --render-thread $RenderThread --quit-after 300 *> $log
            $code=$LASTEXITCODE
        } finally { Pop-Location }
    }else{
        Invoke-GodotFixture -Driver $Driver --path tests/godot res://window_immediate_close.tscn --render-thread $RenderThread --quit-after 300 *> $log
        $code=$LASTEXITCODE
    }
    $output=Get-Content $log -Raw
    if($code -ne 0 -or $output -notmatch 'WINDOW_IMMEDIATE_CLOSE_PASS' -or ([regex]::Matches($output,'WINDOW_IMMEDIATE_CLOSE_CYCLE ')).Count -ne 32 -or $output -match '(?m)^(ERROR:|SCRIPT ERROR:)'){
        throw "Immediate window close failed: $log"
    }
    Write-Output "Immediate window close passed: $log"
} finally { Pop-Location }
